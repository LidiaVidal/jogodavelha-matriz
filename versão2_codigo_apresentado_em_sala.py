import pandas as pd

#Função que altera o tabuleiro e define quem etá jogando
def exibir_tabuleiro(tabuleiro):
    for linha in tabuleiro:
        print(" | ".join(linha))
    print("-" * 15)
def alternar_turno(jogador_atual):
    if jogador_atual == "X":
        return "O"
    else:
        return "X"

# Função que define o jogador
def jogar():
  print("Bem vindo ao jogo da velha")
  nome_x = input("Digite seu nome jogador X: ")
  nome_o = input("Digite seu nome jogador O:")
  jogadores = {"X": nome_x, "O": nome_o}
  Tabuleiro = [ ["□", "□", "□"],["□", "□", "□"],["□", "□", "□"]]
  jogador_atual = "X"

  # Laço de repetição While (enquanto)
  while True:
      LinhaEs = int(input("Escolha a linha (1 a 3): "))
      ColunaEs = int(input("Escolha a coluna (1 a 3): "))
      LinhaEs = LinhaEs - 1
      ColunaEs = ColunaEs - 1

      # Verificação de posição
      if Tabuleiro[LinhaEs][ColunaEs] != "□":
        print("Essa posição já está ocupada! Escolha outra.")
      else:
        Tabuleiro[LinhaEs][ColunaEs] = jogador_atual
        jogador_atual = alternar_turno(jogador_atual)

      # Laço de repetição for (para)
      exibir_tabuleiro(Tabuleiro)
      if Tabuleiro[0][0] == Tabuleiro[0][1] == Tabuleiro[0][2] != "□" or Tabuleiro[1][0] == Tabuleiro[1][1] == Tabuleiro[1][2] != "□" or Tabuleiro[2][0] == Tabuleiro[2][1] == Tabuleiro[2][2] != "□":
          vencedor = alternar_turno(jogador_atual)
          print(f"Temos um vencedor! Parabéns, {jogadores[vencedor]}!")
          break
      if Tabuleiro[0][0] == Tabuleiro[1][1] == Tabuleiro[2][2] != "□" or Tabuleiro[0][2] == Tabuleiro[1][1] == Tabuleiro[2][0] != "□":
          vencedor = alternar_turno(jogador_atual)
          print(f"Temos um vencedor! Parabéns, {jogadores[vencedor]}!")
          break
      if Tabuleiro[0][0] == Tabuleiro[1][0] == Tabuleiro[2][0] != "□" or Tabuleiro[0][1] == Tabuleiro[1][1] == Tabuleiro[2][1] != "□" or Tabuleiro[0][2] == Tabuleiro[1][2] == Tabuleiro[2][2] != "□":
          vencedor = alternar_turno(jogador_atual)
          print(f"Temos um vencedor! Parabéns, {jogadores[vencedor]}!")
          break
      if all("□" not in linha for linha in Tabuleiro):
          print("Deu velha!")
          break
jogar()

