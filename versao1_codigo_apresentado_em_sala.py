Tabuleiro = [ ["□", "□", "□"],["□", "□", "□"],["□", "□", "□"]]

# Laço de repetição While (enquanto)
while True:
    LinhaEs = int(input("Escolha a linha (1 a 3): "))
    ColunaEs = int(input("Escolha a coluna (1 a 3): "))
    LinhaEs = LinhaEs - 1
    ColunaEs = ColunaEs - 1

    # Verificação de posição
    if Tabuleiro[LinhaEs][ColunaEs] != "□":
      print("Essa posição já está ocupada! Escolha outra.")
    else:
       escolha = input("Escolha X ou O: ").upper()
       while escolha != "X" and escolha != "O":
        print("Símbolo inválido! Digite apenas X ou O.")
        escolha = input("Escolha X ou O: ").upper()
       # Armazenamento de posicão na lista
       Tabuleiro[LinhaEs][ColunaEs] = escolha

    # Laço de repetição for (para)
    for linha in Tabuleiro:
        print(linha)
    if Tabuleiro[0][0] == Tabuleiro[0][1] == Tabuleiro[0][2] != "□" or Tabuleiro[1][0] == Tabuleiro[1][1] == Tabuleiro[1][2] != "□" or Tabuleiro[2][0] == Tabuleiro[2][1] == Tabuleiro[2][2] != "□":
        print("Temos um vencedor")
        break
    if Tabuleiro[0][0] == Tabuleiro[1][1] == Tabuleiro[2][2] != "□" or Tabuleiro[0][2] == Tabuleiro[1][1] == Tabuleiro[2][0] != "□":
        print("Temos um vencedor")
        break
    if Tabuleiro[0][0] == Tabuleiro[1][0] == Tabuleiro[2][0] != "□" or Tabuleiro[0][1] == Tabuleiro[1][1] == Tabuleiro[2][1] != "□" or Tabuleiro[0][2] == Tabuleiro[1][2] == Tabuleiro[2][2] != "□":
        print("Temos um vencendor")
        break
    if all("□" not in linha for linha in Tabuleiro):
        print("Deu velha!")
        break
